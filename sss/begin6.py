a = int(input('введите длину ребра a в прямоугольном параллелепипеде: '))
b = int(input('введите длину ребра b в прямоугольном параллелепипеде: '))
c = int(input('введите длину ребра c в прямоугольном параллелепипеде: '))
V = a * b * c
S = 2 * (a*b+b*c+a*c)
print(f'{V}-обьём пр-пар, {S}-площадь пр-пар')